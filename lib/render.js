// render.js — SVG output: the shareable "certificate" card + a small README badge.

function esc(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

function fmt(n) {
  if (n == null) return "?";
  if (n >= 1e6) return (n / 1e6).toFixed(1).replace(/\.0$/, "") + "m";
  if (n >= 1e3) return (n / 1e3).toFixed(1).replace(/\.0$/, "") + "k";
  return String(n);
}

function relDate(iso) {
  if (!iso) return "unknown";
  const ms = Date.now() - new Date(iso).getTime();
  const mins = Math.max(1, Math.round(ms / 60000));
  if (mins < 60) return mins + "m ago";
  const hours = Math.round(mins / 60);
  if (hours < 24) return hours + "h ago";
  const days = Math.round(hours / 24);
  if (days < 31) return days + "d ago";
  return Math.round(days / 30.4) + "mo ago";
}

function truncate(s, max) {
  if (!s) return "";
  return s.length > max ? s.slice(0, max - 1) + "…" : s;
}

const FONT = "'Segoe UI',-apple-system,BlinkMacSystemFont,'Helvetica Neue',Arial,sans-serif";

/**
 * A shareable card, ~496x240, GitHub README friendly.
 * theme=dark | light
 */
function renderCard(data) {
  const light = data.theme === "light";
  const bg = light ? "#ffffff" : "#0d1117";
  const border = light ? "#d0d7de" : "#30363d";
  const fg = light ? "#1f2328" : "#e6edf3";
  const muted = light ? "#656d76" : "#8b949e";
  const panel = light ? "#f6f8fa" : "#161b22";
  const color = data.color || "#8b949e";

  const pct = Math.max(0, Math.min(100, data.vibeIndex || 0));
  const r = 44;
  const cx = 400, cy = 128;
  const circ = 2 * Math.PI * r;
  const arc = (pct / 100) * circ;

  const descLine1 = truncate((data.description || "").slice(0, 70), 70);
  const descLine2 = truncate(trimmedRest(data.description || "", 70), 70);

  return `<svg xmlns="http://www.w3.org/2000/svg" width="496" height="240" viewBox="0 0 496 240" role="img" aria-label="${esc(data.fullName)} vibe index ${pct}%">
  <style>text{font-family:${FONT}}</style>
  <rect width="496" height="240" rx="12" fill="${bg}" stroke="${border}" stroke-width="1"/>
  <text x="24" y="42" font-size="17" font-weight="700" fill="${fg}">${esc(truncate(data.fullName, 40))}</text>
  <text x="24" y="66" font-size="12" fill="${muted}">★ ${esc(fmt(data.stars))}  ·  ${esc(fmt(data.forks))} forks  ·  ${esc(data.language || "unknown")}</text>

  <rect x="24" y="86" width="${185}" height="26" rx="13" fill="${color}"/>
  <text x="116" y="103" font-size="13" font-weight="700" fill="#ffffff" text-anchor="middle">${esc(data.emoji)} ${esc(data.verdict)}</text>

  <text x="24" y="140" font-size="10" fill="${muted}" letter-spacing="1">VIBE INDEX</text>
  <text x="24" y="176" font-size="34" font-weight="800" fill="${color}">${pct}<tspan font-size="16" fill="${muted}">%</tspan></text>
  <text x="24" y="196" font-size="11" fill="${muted}">${esc(descLine1)}</text>
  ${descLine2 ? `<text x="24" y="211" font-size="11" fill="${muted}">${esc(descLine2)}</text>` : ""}
  <text x="24" y="228" font-size="10" fill="${muted}">sampled ${esc(data.signal ? data.signal.sampledCommits : "?")} commits · pushed ${esc(relDate(data.pushedAt))}</text>

  <circle cx="${cx}" cy="${cy}" r="${r}" fill="none" stroke="${panel}" stroke-width="12"/>
  <circle cx="${cx}" cy="${cy}" r="${r}" fill="none" stroke="${color}" stroke-width="12"
    stroke-linecap="round" stroke-dasharray="${arc} ${circ}" transform="rotate(-90 ${cx} ${cy})"/>
  <text x="${cx}" y="${cy + 2}" font-size="30" font-weight="800" fill="${fg}" text-anchor="middle">${pct}</text>
  <text x="${cx}" y="${cy + 22}" font-size="10" fill="${muted}" text-anchor="middle" letter-spacing="1">AI FINGERPRINT</text>

  <text x="472" y="228" font-size="10" fill="${muted}" text-anchor="end">✦ generated by vibelens</text>
</svg>`;
}

function trimmedRest(s, first) {
  return s.length > first ? s.slice(first) : "";
}

/** Small shields-style badge: [ vibe | 83% 🤖 ] */
function renderBadge(data) {
  const label = "vibe";
  const pct = Math.max(0, Math.min(100, data.vibeIndex || 0));
  const value = pct + "%";
  const labelW = 7 * (label.length + 1) + 16;
  const valueW = 7 * value.length + 18;
  const w = labelW + valueW;
  const lw = 7 * label.length;
  const vw = 7 * value.length;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="20" role="img" aria-label="vibe index ${pct}%">
  <style>text{font-family:${FONT}}</style>
  <linearGradient id="s" x2="0" y2="100%">
    <stop offset="0" stop-color="#bbb" stop-opacity=".1"/>
    <stop offset="1" stop-opacity=".3"/>
  </linearGradient>
  <clipPath id="r"><rect width="${w}" height="20" rx="3" fill="#fff"/></clipPath>
  <g clip-path="url(#r)">
    <rect width="${labelW}" height="20" fill="#1f2328"/>
    <rect x="${labelW}" width="${valueW}" height="20" fill="${esc(data.color || "#8b949e")}"/>
    <rect width="${w}" height="20" fill="url(#s)"/>
  </g>
  <text x="${labelW / 2}" y="14" font-size="11" fill="#ffffff" text-anchor="middle">${label}</text>
  <text x="${labelW + valueW / 2 - (pct >= 75 ? 0 : 0)}" y="14" font-size="11" font-weight="700" fill="#ffffff" text-anchor="middle">${value}</text>
</svg>`;
}

module.exports = { renderCard, renderBadge, esc };
